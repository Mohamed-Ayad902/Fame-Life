package org.mayad.fame_life.domain.ai

import org.mayad.fame_life.domain.simulation.AudienceVibe
import kotlin.random.Random

/**
 * The on-device audience. It is used when no backend is configured, when the backend fails, and once the
 * session's AI budget runs out. It reads the latest utterance with [SpeechSignals] and fills short templates,
 * so it still reacts to what was said, but it is deliberately more restrained than the LLM path.
 */
class LocalAudienceGenerator(
    private val seed: Long,
    private val validator: ResponseValidator = ResponseValidator(),
) : AudienceGenerator {

    override suspend fun generate(request: AudienceRequest): AudienceResponse = respond(request)

    fun respond(request: AudienceRequest): AudienceResponse {
        val random = Random(seed * 31 + request.requestSeq)
        val latest = request.recentSpeech.lastOrNull()
        val signals = latest?.let { SpeechSignals.of(it) }
        val arabic = when (request.language) {
            "arabic" -> true
            "mixed" -> signals?.isArabic ?: random.nextBoolean()
            else -> false
        }
        val bank = if (arabic) Lines.arabic else Lines.english
        val vibes = request.vibes.mapNotNull { v -> AudienceVibe.entries.firstOrNull { it.name.equals(v, true) } }.toSet()
        val keyword = signals?.keyword

        val pools = buildList {
            if (signals == null) {
                add(bank.idle to "neutral")
            } else {
                if (signals.isGreeting) add(bank.greeting to "supportive")
                if (signals.isQuestion) add(bank.answer to "curious")
                if (signals.isFunny) add(bank.funny to "funny")
                if (signals.isNegative) add(bank.empathy to "supportive")
                if (signals.isPositive) add(bank.positive to "supportive")
                if (signals.isHype || AudienceVibe.HYPE in vibes) add(bank.hype to "hype")
                bank.topics[signals.topic]?.let { add(it to "curious") }
                if (keyword != null) add(bank.followUp to "curious")
                if (AudienceVibe.FUNNY in vibes) add(bank.funny to "funny")
                add(bank.statement to "neutral")
            }
            if (request.hatersMode && random.nextDouble() < 0.35) add(bank.critical to "critical")
        }

        val count = when {
            signals == null -> 1
            signals.isQuestion || signals.isFunny -> 3
            else -> 2
        }.coerceAtMost(request.maxComments)

        val comments = mutableListOf<CommentDto>()
        var attempts = 0
        while (comments.size < count && attempts < count * 6) {
            attempts++
            val (lines, tone) = pools.random(random)
            val template = lines.random(random)
            if ("{kw}" in template && keyword == null) continue
            val text = template.replace("{kw}", keyword.orEmpty())
            if (comments.none { it.text == text }) comments += CommentDto(text, tone)
        }

        val intensity = when {
            signals == null -> 0.25
            signals.isHype || signals.isFunny -> 0.8
            signals.isPositive || signals.isNegative -> 0.65
            signals.isQuestion -> 0.55
            else -> 0.45
        }
        val suggestion = when {
            signals == null -> null
            signals.isFunny -> "reaction_burst"
            signals.isNegative -> "medium_gift"
            signals.isHype && random.nextDouble() < 0.5 -> "trending"
            signals.isPositive -> "small_gift"
            signals.isGreeting && random.nextDouble() < 0.3 -> "vip_join"
            else -> null
        }
        val dto = AudienceResponseDto(
            comments = comments,
            reactions = buildList {
                if (signals?.isFunny == true) add("laugh")
                if (signals?.isPositive == true || signals?.isNegative == true) add("heart")
                if (signals?.isHype == true) add("fire")
            },
            suggestedEvent = suggestion,
            eventReason = null,
            engagementIntensity = intensity,
            updatedTopic = signals?.topic?.takeIf { it != TopicFamily.NONE }?.name?.lowercase(),
            contextSummary = null,
        )
        return validator.validate(dto, request.hatersMode)
    }


